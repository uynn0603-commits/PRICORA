export function icon(name, className = "h-4 w-4") {
  const key = name
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
  const node = registry[key];
  if (!node) return "";
  const element = createElement(node, {
    class: className,
    "stroke-width": "1.75",
    "aria-hidden": "true",
  });
  return element.outerHTML;
}
